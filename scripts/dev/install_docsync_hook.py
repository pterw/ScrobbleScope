"""Inspect and, only on explicit request, install the docsync preflight hook.

``--check`` (also the default with no flags) is read-only: it resolves and
prints the hook directory Git will actually search from ``cwd``, discloses
every worktree Git knows about (a shared ``core.hooksPath`` or the default
common-directory ``hooks/`` affects all of them, not just the one the
installer happened to run from), and reports whether a wrapper already sits
at the target path. Nothing is written.

``--install`` performs the same disclosure and then, only when given
``--yes``, writes the generated wrapper -- this is the "requires acceptance
of disclosed common-hook scope" the task brief asks for: the scope is always
printed first, and a bare ``--install`` alone is a dry run.

The generated wrapper preserves this repository's existing Graphify hooks:
it never touches ``core.hooksPath``, and it refuses to overwrite a hook file
that is not one this installer generated (an "unknown" wrapper), rather than
guessing that it is safe to replace. See "Commit preflight" in
docs/superpowers/specs/2026-09-15-docsync-closeout-archives-design.md.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

from scripts.dev._worktree_guard_venv import (  # noqa: E402
    POSIX_TOOLS,
    WINDOWS_TOOLS,
    is_runnable,
)

Runner = Callable[..., subprocess.CompletedProcess]

#: Every generated wrapper carries this exact line, which is how the
#: installer tells its own output apart from a hand-written or third-party
#: hook -- see ``classify_existing_hook``.
GENERATED_MARKER = (
    "# Generated by scripts/dev/install_docsync_hook.py -- DOCSYNC PREFLIGHT WRAPPER."
)
HOOK_NAME = "pre-commit"
PREFLIGHT_SCRIPT = Path("scripts/dev/docsync_preflight.py")


class InstallerError(RuntimeError):
    """A precondition failed before inspection or installation could finish."""


# --------------------------------------------------------------------- #
# Git plumbing                                                           #
# --------------------------------------------------------------------- #


def _run_git(
    args: Sequence[str], *, cwd: Path, runner: Runner = subprocess.run
) -> subprocess.CompletedProcess:
    """Run one Git command as text and return its completed process."""
    return runner(
        ["git", *args], cwd=str(cwd), capture_output=True, text=True, check=False
    )


def git_common_dir(cwd: Path, *, runner: Runner = subprocess.run) -> Path:
    """Return the absolute common Git directory Git reports for ``cwd``."""
    result = _run_git(
        ["rev-parse", "--path-format=absolute", "--git-common-dir"],
        cwd=cwd,
        runner=runner,
    )
    if result.returncode != 0:
        raise InstallerError(
            f"git rev-parse --git-common-dir failed: {result.stderr.strip()}"
        )
    return Path(result.stdout.strip())


def primary_checkout_root(cwd: Path, *, runner: Runner = subprocess.run) -> Path:
    """Return the primary checkout for ``cwd`` (the common dir's parent)."""
    return git_common_dir(cwd, runner=runner).parent


def repo_root(cwd: Path, *, runner: Runner = subprocess.run) -> Path:
    """Return the working tree root Git reports for ``cwd``."""
    result = _run_git(["rev-parse", "--show-toplevel"], cwd=cwd, runner=runner)
    if result.returncode != 0:
        raise InstallerError(
            f"git rev-parse --show-toplevel failed: {result.stderr.strip()}"
        )
    return Path(result.stdout.strip())


def configured_hooks_path(cwd: Path, *, runner: Runner = subprocess.run) -> str | None:
    """Return the raw ``core.hooksPath`` value, or ``None`` if it is unset."""
    result = _run_git(["config", "--get", "core.hooksPath"], cwd=cwd, runner=runner)
    if result.returncode != 0:
        return None
    value = result.stdout.strip()
    return value or None


def resolve_hook_directory(cwd: Path, *, runner: Runner = subprocess.run) -> Path:
    """Return the directory Git will actually search for hooks from ``cwd``.

    Git documents ``core.hooksPath`` as resolved relative to the working
    tree in use, not to the primary checkout -- which is why this
    repository's owner keeps a ``.githooks/`` copy in every clone that wants
    Graphify's hooks active (AGENTS.md / AGENT_NOTES.md say so explicitly).
    An unset value falls back to the common Git directory's own ``hooks/``,
    which every worktree *does* share.
    """
    hooks_path = configured_hooks_path(cwd, runner=runner)
    if hooks_path is None:
        return git_common_dir(cwd, runner=runner) / "hooks"
    candidate = Path(hooks_path)
    if candidate.is_absolute():
        return candidate
    # Against the worktree root, not ``cwd``: Git runs a hook from the top
    # of the working tree, so that is what a relative ``core.hooksPath``
    # resolves against. Resolving against ``cwd`` instead put the wrapper
    # in `<subdir>/.githooks` whenever the installer was run from anywhere
    # but the root -- a write that succeeds, reports success, and leaves
    # the hook somewhere Git will never look.
    return repo_root(cwd, runner=runner) / candidate


def list_worktrees(cwd: Path, *, runner: Runner = subprocess.run) -> list[Path]:
    """Return every worktree Git reports, including the primary checkout."""
    result = _run_git(["worktree", "list", "--porcelain"], cwd=cwd, runner=runner)
    if result.returncode != 0:
        raise InstallerError(f"git worktree list failed: {result.stderr.strip()}")
    paths = []
    for line in result.stdout.splitlines():
        if line.startswith("worktree "):
            paths.append(Path(line[len("worktree ") :]))
    return paths


def _is_under(path: Path, boundary: Path) -> bool:
    """Whether ``path`` equals or sits beneath ``boundary``, both resolved."""
    try:
        path.resolve().relative_to(boundary.resolve())
        return True
    except ValueError:
        return False


def hook_directory_is_contained(
    hook_directory: Path, *, worktree_root: Path, common_dir: Path
) -> bool:
    """Whether the resolved hook directory stays inside a trusted boundary.

    A configured ``core.hooksPath`` is an arbitrary string: an absolute path
    outside the repository entirely, or a relative one laced with ``..``,
    would make ``--install`` write a Git hook file somewhere this
    repository does not own. The only two locations this installer trusts
    are the worktree it was asked to act on and the shared common Git
    directory (where the default, unconfigured ``hooks/`` already lives).
    Resolving both sides here (not just trusting the caller's inputs)
    collapses any ``..`` segments before the comparison, so an escape is
    caught even when ``resolve_hook_directory`` returned an unnormalized
    path.
    """
    return _is_under(hook_directory, worktree_root) or _is_under(
        hook_directory, common_dir
    )


# --------------------------------------------------------------------- #
# Interpreter resolution                                                 #
# --------------------------------------------------------------------- #


def qualified_python(
    primary_root: Path,
    *,
    os_name: str = None,
    access: Callable[..., bool] = None,
) -> Path:
    """Return the primary checkout's qualified Python, or fail closed.

    Mirrors ``docsync_preflight.require_python``: installing a wrapper that
    invokes an unqualified interpreter would reproduce, at commit time on
    every future commit, exactly the retired-environment hazard AGENTS.md
    Environment Setup already warns about.
    """
    os_name = os.name if os_name is None else os_name
    access = os.access if access is None else access
    table = WINDOWS_TOOLS if os_name == "nt" else POSIX_TOOLS
    candidate = primary_root / ".venv" / table["python"]
    if not is_runnable(candidate, os_name=os_name, access=access):
        raise InstallerError(
            f"No qualified Python interpreter at {candidate}. Follow the "
            "AGENTS.md Environment Setup section in the primary checkout "
            "before installing this hook."
        )
    return candidate


# --------------------------------------------------------------------- #
# Hook content                                                           #
# --------------------------------------------------------------------- #


def render_hook_script(*, python_exe: Path, preflight_script: Path) -> str:
    """Render the generated wrapper's exact text, always LF-terminated.

    Docsync runs first and unconditionally, before any other pre-commit
    hook can touch the candidate: that ordering is the whole point of this
    wrapper (see ".pre-commit-config.yaml" and the "Commit preflight"
    design section) -- unless the operator named this hook's own id,
    ``doc-state-sync-check``, in ``SKIP`` (pre-commit's own comma-separated
    skip list). That is the one owner-approved local escape for a commit
    that must touch docsync's own control-plane code, which the preflight
    step otherwise refuses on principle; disabling hooks outright is a
    forbidden practice this wrapper does not offer (see AGENTS.md /
    CLAUDE.md). Skipping only bypasses the preflight step below -- delegation
    to pre-commit's own hooks always still happens, and pre-commit applies
    the same SKIP value again there, independently, for every hook it runs.
    It then delegates to ``pre_commit hook-impl`` directly -- the same
    low-level entry point ``pre-commit install`` itself generates -- instead
    of through Git's own hook dispatch, which is what keeps this
    non-recursive: ``hook-impl`` runs the configured hooks in-process and
    never re-enters ``core.hooksPath``.
    """
    python_posix = python_exe.as_posix()
    preflight_posix = preflight_script.as_posix()
    lines = [
        "#!/bin/sh",
        GENERATED_MARKER,
        "# Do not edit by hand; re-run scripts/dev/install_docsync_hook.py "
        "--install --yes to regenerate.",
        "#",
        "# Docsync runs first and unconditionally, before any other",
        "# pre-commit hook can touch the candidate -- unless SKIP names",
        "# this hook's own id below, which is the one owner-approved local",
        "# escape for a commit that must touch docsync's own control-plane",
        "# code. This wrapper then delegates to `pre_commit hook-impl`",
        "# directly instead of through git's own hook dispatch, which is",
        "# what keeps it non-recursive: hook-impl runs the configured",
        "# hooks in-process and never re-enters hooksPath.",
        'case ",$SKIP," in',
        "    *,doc-state-sync-check,*)",
        "        skip_docsync=1",
        "        ;;",
        "    *)",
        "        skip_docsync=0",
        "        ;;",
        "esac",
        'if [ "$skip_docsync" -ne 1 ]; then',
        f'    "{python_posix}" "{preflight_posix}" --staged',
        "    status=$?",
        '    if [ "$status" -ne 0 ]; then',
        '        exit "$status"',
        "    fi",
        "fi",
        f'exec "{python_posix}" -m pre_commit hook-impl '
        '--config=.pre-commit-config.yaml --hook-type=pre-commit -- "$@"',
        "",
    ]
    return "\n".join(lines)


def classify_existing_hook(path: Path) -> str:
    """Classify what occupies ``path``: ``absent``, ``ours``, or ``unknown``."""
    if not path.exists():
        return "absent"
    try:
        content = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return "unknown"
    return "ours" if GENERATED_MARKER in content else "unknown"


