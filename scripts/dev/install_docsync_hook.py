# Inspection / installation report                                       #
# --------------------------------------------------------------------- #


@dataclass(frozen=True)
class Disclosure:
    """Everything a caller must see before this installer may write anything."""

    primary_root: Path
    hooks_path_config: str | None
    hook_directory: Path
    hook_path: Path
    worktrees: tuple[Path, ...]
    existing_status: str

    def render(self) -> str:
        """Render the disclosure the same way for --check and --install."""
        lines = [
            f"Primary checkout: {self.primary_root}",
            (
                f"core.hooksPath: {self.hooks_path_config}"
                if self.hooks_path_config is not None
                else "core.hooksPath: (unset; using the common .git/hooks directory)"
            ),
            f"Resolved hook directory: {self.hook_directory}",
            f"Target hook file: {self.hook_path}",
            f"Existing hook file: {self.existing_status}",
            f"Worktrees this hook directory affects ({len(self.worktrees)}):",
        ]
        lines.extend(f"  - {worktree}" for worktree in self.worktrees)
        return "\n".join(lines)


def inspect(cwd: Path, *, runner: Runner = subprocess.run) -> Disclosure:
    """Build the full disclosure for ``cwd`` without writing anything."""
    primary_root = primary_checkout_root(cwd, runner=runner)
    hooks_path_config = configured_hooks_path(cwd, runner=runner)
    hook_directory = resolve_hook_directory(cwd, runner=runner)
    hook_path = hook_directory / HOOK_NAME
    worktrees = tuple(list_worktrees(cwd, runner=runner))
    return Disclosure(
        primary_root=primary_root,
        hooks_path_config=hooks_path_config,
        hook_directory=hook_directory,
        hook_path=hook_path,
        worktrees=worktrees,
        existing_status=classify_existing_hook(hook_path),
    )


def install(
    cwd: Path,
    *,
    runner: Runner = subprocess.run,
    yes: bool = False,
    os_name: str = None,
    access: Callable[..., bool] = None,
    print_fn: Callable[[str], None] = print,
) -> int:
    """Disclose scope, then write the wrapper only when ``yes`` is true.

    Returns 0 on a successful install (or a no-op dry run), 2 when a
    precondition fails (missing interpreter, an unknown existing hook, an
    out-of-repository target, or a Git failure).
    """
    try:
        disclosure = inspect(cwd, runner=runner)
        worktree_root = repo_root(cwd, runner=runner)
        common_dir = git_common_dir(cwd, runner=runner)
    except InstallerError as exc:
        print_fn(f"ERROR {exc}")
        return 2

    print_fn(disclosure.render())

    # Containment is enforced only here, by --install -- never by --check
    # (`inspect()` above), which stays purely informational so an operator
    # can still see an unsafe configured target without this function
    # refusing on their behalf before they asked it to write anything.
    if not hook_directory_is_contained(
        disclosure.hook_directory, worktree_root=worktree_root, common_dir=common_dir
    ):
        print_fn(
            f"ERROR {disclosure.hook_directory} is outside this repository "
            f"(neither the worktree at {worktree_root} nor the common Git "
            f"directory at {common_dir}). Refusing to install a hook there "
            "-- fix core.hooksPath, or run this installer from the "
            "checkout that value is meant for."
        )
        return 2

    if not yes:
        print_fn(
            "Dry run: nothing was written. Pass --yes to install the wrapper "
            "at the target hook file shown above."
        )
        return 0

    if disclosure.existing_status == "unknown":
        print_fn(
            f"ERROR {disclosure.hook_path} already exists and was not "
            "generated by this installer. Refusing to overwrite it -- move "
            "it aside (or fold its logic into the wrapper by hand) and "
            "re-run this installer."
        )
        return 2

    try:
        python_exe = qualified_python(
            disclosure.primary_root, os_name=os_name, access=access
        )
    except InstallerError as exc:
        print_fn(f"ERROR {exc}")
        return 2

    preflight_script = disclosure.primary_root / PREFLIGHT_SCRIPT
    script_text = render_hook_script(
        python_exe=python_exe, preflight_script=preflight_script
    )
    disclosure.hook_directory.mkdir(parents=True, exist_ok=True)
    # write_bytes, not write_text: write_text's default newline handling
    # translates every "\n" to the platform line separator, which on
    # Windows would reintroduce the exact CRLF-hook failure AGENTS.md /
    # AGENT_NOTES.md already document for `.githooks/post-commit` under
    # Git for Windows' `sh`.
    disclosure.hook_path.write_bytes(script_text.encode("utf-8"))
    if os.name != "nt":
        os.chmod(disclosure.hook_path, 0o755)

    verb = "Reinstalled" if disclosure.existing_status == "ours" else "Installed"
    print_fn(f"{verb} the docsync preflight wrapper at {disclosure.hook_path}.")
    return 0


# --------------------------------------------------------------------- #
# CLI                                                                     #
# --------------------------------------------------------------------- #


def _build_parser() -> argparse.ArgumentParser:
    """Declare the read-only default, the explicit apply, and its gate."""
    parser = argparse.ArgumentParser(
        description=(
            "Inspect (default) or install the docsync-first pre-commit hook wrapper."
        )
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Read-only inspection (the default; writes nothing).",
    )
    parser.add_argument(
        "--install",
        action="store_true",
        help="Disclose scope and, only with --yes, write the wrapper.",
    )
    parser.add_argument(
        "--yes",
        action="store_true",
        help="Required alongside --install to actually write the wrapper.",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Parse arguments and run inspection or the gated install."""
    args = _build_parser().parse_args(argv)
    if args.check and args.install:
        print("Use --check or --install, not both.", file=sys.stderr)
        return 2
    cwd = Path.cwd()
    if args.install:
        return install(cwd, yes=args.yes)
    print(inspect(cwd).render())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
